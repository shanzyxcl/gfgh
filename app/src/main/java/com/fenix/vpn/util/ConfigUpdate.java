    public void start(boolean isOnCreate, String tipo) {
        this.tipo = tipo;

        if (!isOnCreate) /*showDialog()*/;

        ExecutorService executor = Executors.newSingleThreadExecutor();
        Handler handler = new Handler(Looper.getMainLooper());

        executor.execute(() -> {
            String result = doInBackground();
            handler.post(() -> {
                if (!isOnCreate && progressDialog != null) {
                    progressDialog.dismiss();
                }
                if (listener != null) {
                    listener.onUpdateListener(result);
                }
            });
        });
    }

    public interface OnUpdateListener {
        void onUpdateListener(String result);
    }

    private String doInBackground() {
        try {
            String urlStr;
            switch (tipo) {
                case "usuarios":
                    urlStr = users;
                    break;
                case "servidores":
                    urlStr = servers;
                    break;
                case "anuncios":
                    urlStr = anuncios;
                    break;
                default:
                    return "Tipo invalid";
            }

            StringBuilder sb = new StringBuilder();
            URL url = new URL(urlStr);
            HttpURLConnection conn = (HttpURLConnection) url.openConnection();
            conn.setRequestMethod("GET");
            conn.connect();

            BufferedReader br = new BufferedReader(new InputStreamReader(conn.getInputStream()));
            String response;
            while ((response = br.readLine()) != null) {
                sb.append(response);
            }

            return sb.toString();
        } catch (Exception e) {
            return "Error Si Persiste Contacta Al Admin: " + e.getMessage();
        }
    }

